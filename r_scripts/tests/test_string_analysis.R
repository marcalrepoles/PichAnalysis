source("r_scripts/lib/string_analysis.R")
stopifnot(requireNamespace("igraph",quietly=TRUE))
nodes<-function(ids)data.frame(string_protein_id=ids,preferred_name=ids,gene_symbol=ids,hop_level=rep(0L,length(ids)),seed_support_count=rep(0L,length(ids)))
edges<-function(a,b,score=800)data.frame(protein_a=a,protein_b=b,combined_score=score,experiments=score-100,experiments_transferred=rep(7,length(score)))
path<-string_node_metrics(nodes(c("A","B","C")),edges(c("A","B"),c("B","C")))
stopifnot(identical(path$network_degree,c(1L,2L,1L)),path$betweenness[2]==1,all(path$component_size==3),is.nan(path$local_clustering_coefficient[1]),path$local_clustering_coefficient[2]==0,is.nan(path$local_clustering_coefficient[3]))
triangle<-string_node_metrics(nodes(c("A","B","C")),edges(c("A","B","A"),c("B","C","C")))
stopifnot(all(triangle$network_degree==2),all(triangle$local_clustering_coefficient==1))
star<-string_node_metrics(nodes(c("A","B","C","D")),edges(rep("A",3),c("B","C","D")))
stopifnot(star$network_degree[1]==3,sum(star$network_degree>=3)==1,star$betweenness[1]>0)
disconnected<-string_node_metrics(nodes(c("A","B","C")),edges("A","B"))
stopifnot(length(unique(disconnected$component_id))==2,is.na(disconnected$closeness[3]),disconnected$network_degree[3]==0)
empty<-string_node_metrics(nodes("A"),edges(character(),character(),numeric()))
stopifnot(nrow(empty)==1,empty$network_degree==0,is.na(empty$closeness))
evidence<-string_evidence_summary(edges(c("A","A"),c("B","C"),c(800,400)))
stopifnot(setequal(evidence$channel,c("experiments","experiments_transferred")),all(evidence$edges_with_nonzero_score==2))
output<-file.path(tempdir(),"string_plot_test");string_plot(path,"network_degree","string_protein_id","Degree",output)
stopifnot(file.exists(paste0(output,".png")),file.exists(paste0(output,".pdf")))
cat("R STRING tests passed: path, triangle, star, disconnected, isolate, evidence, plots\n")
